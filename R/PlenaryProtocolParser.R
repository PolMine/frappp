#' Parser for Plenary Protocols.
#' 
#' The PlenaryProtocolParser implements a generic workflow to parse protocols
#' and to generate XML output that complies with the specifications of the Text
#' Encoding Initiative (TEI).
#' 
#' @section Usage:
#' PPP <- PlenaryProtocolParser$new()
#' 
#' @examples
#' PPP <- PlenaryProtocolParser$new()
#' PPP$speaker_regex <- list(
#'   pres = list(
#'     regex = "^(The\\s+President):\\s*(.+)$",
#'     fn = function(who, txt) c(who = who, role = "presidency", text = txt)
#'   ),
#'   sg = list(
#'     regex = "^(The\\sSecretary-General):\\s*(.+)$",
#'     fn = function(who, txt) c(who = who, role = "sg", text = txt)
#'   )
#' )
#' PPP$speaker_mismatch <- character()
#' PPP$agenda_item_regex <- c(any = "^Item\\s+\\d+\\sof.*agenda.*$")
#' PPP$agenda_item_types <- c(any = "debate")
#' PPP$stage_regex <- c(end = "^\\s*The\\s+meeting\\s+rose\\s+at\\s+\\d+\\s[ap]\\.m\\.\\s*$")
#' 
#' PPP$read_file(filename = system.file(package = "frappp", "txt", "UNGA_71_1.txt"))
#' PPP$add_metadata(
#'   c(legislativePeriod = "71", sessionNo = "1", date = "2016-09-13",
#'   publisher = "UN", url = "www.un.org", filetype = "pdf", retrievalDate = "2018-03-15"
#'   )
#' )
#' PPP$make_header()
#' PPP$preprocessing()
#' PPP$split_by_speakers()
#' PPP$reconstruct_paragraphs()
#' PPP$make_body()
#' outfile <- tempfile()
#' cat(as.character(PPP$xml))
#' @format \code{\link{R6Class}} object.
#' @field id id of the document processed, used for matching
#' @field txt character vector, the plain text of the document
#' @field chunks list of character vectors, the plain text chunked by applying
#'   the regular expressions to detect speakers
#' @field xml object of class \code{xml_document} (from package \code{xml2}),
#'   the XML document that is constructed
#' @field metadata a named character vector with metadata for the document; the
#'   names of the vector are used to get the matching XPath expression to insert
#'   the data into the TEI header
#' @field chunk_data a \code{data.frame} generated by the \code{$get_chunk_data()}
#'   method, generated by applying the regular expressions for speakers and
#'   corresponding functions
#' @field xpath a named vector of XPath expressions used to find the node in the
#'   TEI header where metadata should be inserted; names are used to link
#'   metadata XPath expressions
#' @field preprocessing_functions a named list of functions that is applied on
#'   the plain text (slot $txt); the names are ids, to link documents and
#'   functions
#' @field stage_regex a named vector of regular expressions to detect whether a
#'   line is a stage instruction; when constructing the document, the name of
#'   the matching regex will become the value of the 'type' attribute
#' @field speaker_regex a named list of named lists that need to include a
#'   regular expression to match a type of speaker (entry "regex") and a
#'   function (entry "fn") that is passed into \code{strapply} (package
#'   \code{gsubfn}) to turn the match into the speaker attributes; the return
#'   value of the function needs to be a named character vector, and all
#'   functions in the speaker_regex list need to return equivalent vectors (same
#'   length, same names)
#' @field speaker_mismatch a character vector of mismatches for speakers; the
#'   matches for speakers on this list will not be annotated
#' @field agenda_item_regex a named character vector of regular expressions to
#'   detect calls to agenda items
#' @field agenda_item_types a named character vector of keywords that may occurr
#'   in titles of agenda items; if one of these keywords occurs, the type of the
#'   debate will be set according to the name of the string
#' @field agenda_item_mismatch a character vector of potential mismatches for
#'   agenda items; if a match for an agenda item is included in this vector, it
#'   will not be annotated
#' @field agenda_item_maximum_nchar_desc maximum number of characters to extract
#'   as value of attribute describing an agenda item
#' 
#' @section Arguments:
#' \describe{
#'   \item{\code{xpath}}{named character vector of XPath expressions to find nodes in
#'   TEI document where metadata should be inserted}
#'   \item{\code{filename}}{filename (full path) to read in / for output}
#'   \item{\code{id}}{id of the document being processd}
#'   \item{\code{metadata}}{named character vector with metainformation}
#'   \item{\code{replacements}}{list of length 2 character vectors, providing regular expressions and replacements (as input to \code{gsub})}
#'   \item{\code{exclude}}{types of speakers not to consider when reconstructing paragraphs}
#'   \item{\code{threshold}}{for reconstructing paragraphs, number of characters when to concatenate lines}
#'   \item{\code{parent}}{an XML node, where to put speaker node}
#'   \item{\code{chunk_no}}{integer vecotr, chunk in the field $chunks to process}
#'   \item{\code{chunk_nos}}{integer vector, chunks in the field $chunks to process}
#'   \item{\code{template}}{filename of a template of a TEI document}
#'   \item{\code{regex}}{a regular expression}
#'   \item{\code{nchar_context}}{integer, number of characters in the context of regex}
#'   \item{\code{verbose}}{logical, whether to output messages }
#'   \item{\code{n}}{the number of lines that will maximally be collapsed to
#'   check whether one of the regular expressions in $stage_regex matches}
#' }
#' @section Methods:
#' \describe{
#'   \item{\code{$new(xpath = teiXpath)}}{initialize a new object of class
#'   \code{PlenaryProtocolParser}; assigns the default XPath expressions}
#'   \item{\code{$read_file = function(filename, id = basename(filename),
#'   metadata = c(birthday = as.character(Sys.Date()), package = "frappp",
#'   version = as.character(packageVersion("frappp"))) )}}{read in a new plain
#'   text file, assign id and metadata, and reset all document-specific data in
#'   the Parser}
#'   \item{\code{$preprocessing(replacements = list(c("[\025]", "\u00A7"),
#'   c("\u00A0", " "), c("\a", "\n"))}}{ the method will (a) remove empty lines,
#'   (b) remove leading and trailing whitespace, (c) carry out replacements, and
#'   (d) carry out document-specific functions, getting the respective function
#'   from the list of functions in field \code{$preprocessing_functions}, and
#'   using the document id to get the right function}
#'   \item{\code{$get_metadata()}}{extract metadata from document; not defined
#'   for parent class}
#'   \item{\code{$add_metadata(metadata)}}{add metadata (named character vector) to what
#'   is already present in field $metadata; }
#'   \item{\code{$get_debate()}}{remove leading and trailing noise before the
#'   "actual debate" (such as table of contents, or annexes); undefined for
#'   parent class}
#'   \item{\code{$split_by_speakers()}}{turn the plain text
#'   document into a list of chunks by applying regular expressions for
#'   speakers}
#'   \item{\code{get_chunk_data()}}{extract speaker data by
#'   applying regular expressions in $speaker_regex; the result is stored in the
#'   field $chunk_data}
#'   \item{\code{$detect_stage_instructions(n = 2L)}}{Identify stage instructions (such as interjections etc.) by applying 
#'   the regular expressions in the field \code{stageRegex}; to be able to cope with multiline stage
#'   instructions, lines will be concatenated successively. If multiple regexes might match, only the 
#'   first match will be found in the result. The same is true for the number of lines.}
#'   \item{\code{$reconstruct_paragraphs(exclude = "pres")}}{This function
#'   concatenates paragraphs that are splitted (i.e. the text does not end with
#'   an interpuncutation) by applying a regex. It includes an exlude parameter:
#'   The formalities in the protocols explained by the president may include
#'   much more than spoken text.}
#'   \item{\code{$make_speaker_nodes(chunk_nos, parent)}}{Iterate through the
#'   chunks (i.e. list of character vectors in the field \code{chunks}) and add
#'   nodes for speakers in the TEI document (in the field \code{xml})) at the
#'   node provided by parent.}
#'   \item{\code{make_speaker_node(chunk_no, parent)}}{add chunk defined by chunk_no
#'   as a single speaker node as child to node defined by parent; usually not
#'   called directly}
#'   \item{\code{get_agenda_item_calls(maxNcharAgendaItemDesc = 40)}}{apply
#'   $agenda_item_regex and get calls to agenda items, the return value is a
#'   data.frame with information on agenda item calls}
#'   \item{\code{make_header(template = system.file("xml", "teiTemplate.xml",
#'   package = "frappp"))}}{ Generate the header of the XML output document,
#'   taking the template provided as the point of departure; data in the field
#'   $metadata will be inserted by using XPath expression in the field $xpath,
#'   using names of the vectors to match matters}
#'   \item{\code{make_body()}}{generate body of the XML
#'   document by turning chunks and respective chunk_data into XML; interjections
#'   will be annotated based on on $stage_regex; an annotation of agenda
#'   items is done when field $agenda_item_regex is not NULL}
#'   \item{\code{$xmlify()}}{carry out all steps from
#'   reading in text to saving XML output; a prerequisite is that the parser has
#'   been configured}
#'   \item{\code{browse_xml()}}{output XML document in field $xml in browser}
#'   \item{\code{save_xml(filename)}}{save XML document based on content of field
#'   $xml}
#'   \item{\code{browse_txt()}}{output plain text in browser}
#'   \item{\code{show_nchar_histogram()}}{utility function, show histogram of the
#'   length of the character strings in the vector in $txt; useful to determine
#'   the number of characters for paragraph reconstruction}
#'   \item{\code{regex_context_in_chunks(regex, nchar_context = 100, verbose =
#'   FALSE)}}{get matches for \code{regex} and return \code{data.frame} with matches 
#'   in their context}
#'}
#' @export PlenaryProtocolParser
#' @importFrom stringi stri_locate_all_regex
#' @aliases agendaItemTypes teiXpath
#' @importFrom xml2 read_xml xml_find_first xml_text<- xml_text xml_attrs xml_attrs<- xml_add_child xml_find_all xml_name xml_children
#' @importFrom gsubfn strapply strapplyc
#' @importFrom R6 R6Class
#' @importFrom markdown markdownToHTML
PlenaryProtocolParser <- R6Class(
  
  "PlenaryProtocol",
  
  public = list(
    
    # fields
	  id = NULL,
    
    txt = NULL, # character
		chunks = NULL, # list
		xml = NULL, # an xml document (from xml2 package)
		html = NULL, # character
		
		metadata = NULL, # list
		chunk_data = NULL,
		xpath = NULL, # list

		preprocessing_functions = NULL, # list
		
		stage_regex = NULL,

		speaker_regex = NULL, # list
		speaker_mismatch = NULL, # character
		speaker_maximum_nchar_name = NULL,
		
		agenda_item_regex = NULL, # list
		agenda_item_types = NULL, # character
		agenda_item_mismatch = NULL, # list
		agenda_item_maximum_nchar_desc = NULL, # integer
		
		# methods 
		
		initialize = function(xpath = teiXpath){
		  self$xpath = xpath
		  invisible(self)
		},
		
		
		read_file = function(
		  filename, id = basename(filename),
		  metadata = c(birthday = as.character(Sys.Date()), package = "frappp", version = as.character(packageVersion("frappp")))
		  ){
		  
		  if (!is.null(self$chunks)) self$chunks <- NULL
		  if (!is.null(self$xml)) self$xml <- NULL
		  if (!is.null(self$html)) self$html <- NULL
		  
		  self$metadata <- metadata
		  
		  self$txt <- readLines(filename)  
		  self$id <- id
		  
		  invisible(self)
		},
		
		
		preprocessing = function(replacements = list(c("[\025]", "\u00A7"), c("\u00A0", " "), c("\a", "\n"))){
		  
		  # remove empty lines
		  emptyLines <- grep("^\\s*$", self$txt)
		  if (length(emptyLines) > 0) self$txt <- self$txt[-emptyLines]
		  
		  # remove leading and trailing whitespace
		  self$txt <- gsub("^\\s*(.*)\\s*$", "\\1", self$txt)
		  
		  # carry out replacements
		  for (replacement in replacements){
		    self$txt <- gsub(replacement[1], replacement[2], self$txt)
		  }
		  
		  # execute document-specific preprocessing functions
		  if (self$id %in% names(self$preprocessing_functions)){
		    txt <- self$preprocessing_functions[[self$id]](self$txt)
		  }
		  
		  invisible(self)
		},
		
		add_metadata = function(metadata){
		  if (is.null(names(metadata))) stop("the input character vector needs to be named")
		  if (any(names(metadata) == "")) stop("all elements of the character vector need to be named")
		  if (length(unique(names(metadata))) != length(names(metadata))) stop("all names of the character vectors neet to be unique")
		  self$metadata <- c(self$metadata, metadata)
		  invisible(self)
		},
		
		
		get_metadata = function(){
		  warning("needs to be implemented for specific protocol types")
		},
		
		
		get_debate = function(){
		  warning("needs to be implemented for specific protocol types")
		},
		
		get_chunk_data = function(){
		  matchTables <- lapply(
		    names(self$speaker_regex),
		    function(speakerRegexType) {
		      matchList <- strapply(
		        self$txt,
		        pattern = self$speaker_regex[[speakerRegexType]][["regex"]],
		        FUN = self$speaker_regex[[speakerRegexType]][["fn"]],
		        perl = TRUE
		      )
		      if (all(sapply(matchList, is.null))) return(NULL)
		      names(matchList) <- as.character(1:length(matchList))
		      matchMatrix <- do.call(rbind, matchList)
		      matchDf <- data.frame(
		        regex = speakerRegexType,
		        index = as.integer(rownames(matchMatrix)),
		        matchMatrix,
		        stringsAsFactors = FALSE
		      )
		      if (!is.null(self$speaker_maximum_nchar_name)){
		        matchDf <- matchDf[which(nchar(matchDf[,"who"]) <= self$speaker_maximum_nchar_name),]
		      }
		      
		      matchDf
		    }
		  )
		  matchTable <- do.call(rbind, matchTables)
		  
		  checkedMatches <- which(!matchTable[["who"]] %in% self$speaker_mismatch)
		  if (length(checkedMatches) != nrow(matchTable)) matchTable <- matchTable[checkedMatches,]
		  
		  matchTable <- matchTable[order(matchTable[["index"]]),]
		  self$chunk_data <- plyr::ddply(.data = matchTable, .variables = "index", .fun = function(df){
		    if (nrow(df) > 1){
		      firstRegexMatched <- names(self$speaker_regex)[which(names(self$speaker_regex) %in% df[["regex"]])][1]
		      df <- df[which(df[["regex"]] == firstRegexMatched),]
		      return(df[1,])
		    } else {
		      return(df)
		    }
		  })
		  invisible(self)
		},
		
		split_by_speakers = function(){
		  
		  # The first step is to get the indices of the vector where a call to a speaker occurs.
		  # We iterate through the list provided by the 'speakerRegex' field, and get the
		  # index positions. Two checks are performed: (a) If the match for the name of the
		  # speaker exceeds 'maxLengthWho', the match is discarded. (b) Matches that are 
		  # included in the field 'speaker_mismatch' are discarded, too.
		  
		  self$get_chunk_data()
		  

		  # Intermediate step: We now turn the list of starting paragraphs into a
		  # oredered, named character vector.
		  startParas <- self$chunk_data[["index"]]
		  if (startParas[length(startParas)] != length(self$txt)){
		    startParas <- c(startParas, length(self$txt))
		  }
		  
		  # Finally, the raw character vector is chunked, i.e. it is turned into a list
		  # with sections of speech of one speaker that has been identified.
		  parasSpeechesFactor <- cut(1:length(self$txt), breaks = startParas, include.lowest = TRUE, right = FALSE)
		  self$chunks <- split(self$txt, parasSpeechesFactor)
		  names(self$chunks) <- names(startParas)[1:length(self$chunks)]
		  
		  invisible(self)
		},
		
		
		detect_stage_instructions = function(n = 2L){
		  if (is.null(self$stage_regex)){
		    warning("field $stage_regex is NULL - no regular expressions defined to detect stage instructions; ",
		            "returning object unchanged")
		    return(self)
		  }
		    
		  if (n <= 1L) stop("detect_stage_instructions-method: n needs to be an integer value of 1 or higher")
		  txt <- self$txt
		  names(txt) <- rep(x = "", times = length(txt))
		  for (i in 1L:n){
		    vecs <- sapply(1L:i, function(j) txt[j:(length(txt) - (i - j))])
		    collapsed <- apply(vecs, 1, function(x) paste0(x, collapse = " "))
		    for (regexID in 1L:length(self$stage_regex)){
		      matches <- which(grepl(self$stage_regex[[regexID]], collapsed) == TRUE)
		      for (m in rev(matches)){
		        if (all(names(txt)[m:(m + i - 1L)] == "")){
		          txt[m] <- collapsed[m]
		          names(txt)[m] <- names(self$stage_regex)[[regexID]]
		          if (i > 1L) txt <- txt[-((m + 1L):(m + i - 1L))] 
		        }
		      }
		    }
		  }
		  self$txt <- txt
		  invisible(self)
		},
		
		
		reconstruct_paragraphs = function(exclude = "pres", threshold = 40){
		  # The general scheme is that we iterate through the chunks. Thus there 
		  # is a helper function '.chunkProcessor' to handle the individual chunks.
		  .processor <- function(chunk){
		    if (length(chunk) > 1){
		      # Each chunk is turned into a list of character vectors. The assumption here is
		      # that concatenating paragraphs is not performed for interjections.
		      stage <- unique(unlist(lapply(self$stage_regex, function(regex) grep(regex, chunk))))
		      cutPoints <- unique(c(1, stage - 1, stage, length(chunk)))
		      cutPoints <- cutPoints[order(cutPoints)]
		      sections <- cut(
		        x = 1:length(chunk), breaks = cutPoints,
		        include.lowest = TRUE, right = TRUE
		        )
		      subchunks <- split(chunk, sections)
		      
		      # iterate through the list of speech and interjections.
		      retval <- lapply(subchunks, function(x) paragraphize(x = x, threshold = threshold))
		      return( unname(unlist(retval)) )
		    } else {
		      return( chunk )
		    }
		  }
		  self$chunks <- lapply(self$chunks, .processor)
		  invisible(self)
		},
		
		
		get_agenda_item_calls = function(){
		  
		  chunkTypes <- gsub("(.*?)\\d+", "\\1", names(self$chunks))
		  chunksToConsider <- which(chunkTypes == "pres")

		  matchesForTopicCall <- lapply(
		    
		    chunksToConsider,
		    
		    function(i){
		      chunk <- self$chunks[[i]]
		      
		      # get the lines where one of agenda item regexes matches
		      matchAgendaItemCall <- unique(unlist(lapply(self$agenda_item_regex, function(regex) grep(regex, chunk))))
		      if (length(matchAgendaItemCall) == 0) return( NULL )
		      
		      # remove the matching lines that are known to be mismatches
		      mismatches <- self$agenda_item_mismatch[[self$filename]]
		      if (!is.null(mismatches)){
		        agendaItemMismatchPosition <- unique(unlist(
		          lapply(mismatches, function(mismatch) grep(mismatch, chunk)
		          )))
		        if (length(agendaItemMismatchPosition) > 0) matchAgendaItemCall <- matchAgendaItemCall[-agendaItemMismatchPosition]
		      }
		      if (length(matchAgendaItemCall) == 0) return( NULL ) # stop things if nothing left
		      
		      matchPosition <- max(matchAgendaItemCall) # apply only last call of an agenda item
		      if (matchPosition > length(chunk)) return( NULL ) # no idea how it can happen, but it happened 
		      
		      # which of the regexes did the hit?
		      matchRegexLogical <- sapply(self$agenda_item_regex, function(regex) grepl(regex, chunk[matchPosition]))
		      regexName <- names(matchRegexLogical)[which(matchRegexLogical == TRUE)]
		      
		      if (any(regexName != "any")){
		        agendaItemType <- regexName[which(regexName != "any")][1]
		        agendaItemDesc <- unname(self$agenda_item_types[agendaItemType])
		      } else if (matchPosition < length(chunk)){
		        agendaItemTitle <- chunk[matchPosition + 1]
		        agendaItemTypeMatch <- sapply(self$agenda_item_types, function(regex) grepl(regex, agendaItemTitle))
		        agendaItemType <- paste(names(agendaItemTypeMatch[which(agendaItemTypeMatch == TRUE)]), collapse = "|")   
		        if (!is.null(self$agenda_item_maximum_nchar_desc)){
		          agendaItemDesc <- if (nchar(agendaItemTitle) > self$agenda_item_maximum_nchar_desc){
		            paste(substr(agendaItemTitle, 1, self$agenda_item_maximum_nchar_desc), "...", sep = " ")
		          } else {
		            agendaItemTitle
		          }
		        } else {
		          agendaItemDesc <- agendaItemTitle
		        }
		      }
		      data.frame(
		        chunk = i, position = matchPosition, type = agendaItemType, desc = agendaItemDesc,
		        stringsAsFactors = FALSE
		        )
		    }
		  )
		  topicCallDf <- do.call(rbind, matchesForTopicCall)
		  invisible(topicCallDf)
		},
		
		
		make_speaker_node = function(chunk_no, parent){
		  textParas <- self$chunks[[chunk_no]]
		  # remove empty lines, if necessary
		  if (length(grep("^\\s*$", textParas)) > 0) textParas <- textParas[-grep("^\\s*$", textParas)]  
		  
		  type <- gsub("^(.*?)\\d+$", "\\1", names(self$chunks)[[chunk_no]])
		  
		  speakerAttrs <- unlist(self$chunk_data[chunk_no,])
		  speakerAttrs <- speakerAttrs[-which(names(speakerAttrs) == "regex")]
		  speakerAttrs <- speakerAttrs[-which(names(speakerAttrs) == "index")]
		  speakerAttrs <- speakerAttrs[-which(names(speakerAttrs) == "text")]
		  Encoding(speakerAttrs) <- "UTF-8" # just to be sure
		  
		  split <- strapplyc(textParas[1], "^\\s*(.*?:)\\s*(.*)\\s*$")[[1]]
		  textParas[1] <- split[2]

		  newSpeakerNode <- xml_add_child(.x = parent, .value = "sp")
		  xml_attrs(newSpeakerNode) <- speakerAttrs
		  xml_add_child(newSpeakerNode, .value = "speaker", split[1])
		  
		  lapply(
		    textParas,
		    function(para){
		      # the field $stage_regex is not necessarily defined
		      if (!is.null(self$stage_regex)){
		        stageRegexMatch <- sapply(self$stage_regex, function(regex) grepl(regex, para, perl = TRUE))
		      } else {
		        stageRegexMatch <- FALSE
		      }
		      
		      if (any(stageRegexMatch)){
		        # add element for interjection, if respective regex matches
		        stageType <- names(stageRegexMatch)[stageRegexMatch][1]
		        xml_add_child(newSpeakerNode, .value = "stage", type = stageType, para)
		      } else {
		        xml_add_child(newSpeakerNode, .value = "p", para)
		      }
		    }
		  )
		  invisible(type)
		},

		
		make_speaker_nodes = function(chunk_nos, parent){
		  lapply(chunk_nos, function(i) self$make_speaker_node(chunk_no = i, parent = parent))
		  invisible(self)
		},
		
		
		make_header = function(template = system.file("xml", "teiTemplate.xml", package = "frappp")){
		  self$xml <- xml2::read_xml(template)
		  lapply(
		    names(self$xpath),
		    function(x){
		      if (x %in% names(self$metadata)){
		        teiNode <- xml2::xml_find_first(x = self$xml, xpath = self$xpath[[x]])
		        xml2::xml_text(teiNode) <- as.character(self$metadata[[x]])
		      }
		    })
		  invisible(self)
		},
		
		
		make_body = function(){
		  bodyNode <- xml2::xml_find_first(x = self$xml, xpath = "/TEI/text/body")
		  if (!is.null(self$agenda_item_regex)){ # annotate agenda items if regex present
		    self$make_speaker_nodes(chunk_nos = 1:length(self$chunks), parent = bodyNode)
		  } else {
		    topicCallDf <- self$get_agenda_item_calls()
		    if (is.null(topicCallDf)){
		      agendaItemChunks <- list(1:length(self$chunks))
		      topicCallDf <- data.frame(chunk = 1, position = NA, type = NA, desc = NA)
		    } else {
		      topicCallChunks <- topicCallDf[["chunk"]]
		      # to include the last para in the last topic called
		      if (max(topicCallChunks) != length(self$chunks)){
		        topicCallChunks <- c(topicCallChunks, length(self$chunks))
		      }
		      howToCut <- cut(x = 1:length(self$chunks), breaks = topicCallChunks, include.lowest = TRUE)
		      howToCutInt <- as.integer(howToCut)
		      howToCutInt[which(is.na(howToCutInt))] <- 0
		      if (0 %in% howToCutInt){
		        topicCallDf <- rbind(data.frame(chunk = 1, position = NA, type = NA, desc = NA), topicCallDf)
		      }
		      agendaItemChunks <- split(1:length(self$chunks), howToCutInt)
		    }
		    lapply(
		      1:length(agendaItemChunks),
		      function(i){
		        newAgendaItemNode <- xml_add_child(
		          .x = bodyNode, .value = "div", type = "agenda_item", 
		          n = names(agendaItemChunks)[i], what = unname(topicCallDf[i,"type"]), desc = unname(topicCallDf[i,"desc"])
		        )
		        self$make_speaker_nodes(chunk_nos = agendaItemChunks[[i]], parent = newAgendaItemNode)
		      }
