  "PlenaryProtocol",
  
  public = list(
    
    # fields
	  id = NULL,
    
    txt = NULL, # character
		chunks = NULL, # list
		xml = NULL, # an xml document (from xml2 package)
		html = NULL, # character
		
		metadata = NULL, # list
		chunkData = NULL,
		xpath = NULL, # list

		preprocessingFunctions = NULL, # list
		
		stageRegex = NULL,

		speakerRegex = NULL, # list
		speakerMismatch = NULL, # character
		
		agendaItemRegex = NULL, # list
		agendaItemTypes = NULL, # character
		agendaItemMismatch = NULL, # list
		
		# methods 
		
		initialize = function(stageRegex = c(interjection = "^\\s*\\(.*?\\)\\s*$"), xpath = teiXpath){
		  self$stageRegex <- stageRegex
		  self$xpath = xpath
		  invisible(self)
		},
		
		
		readFile = function(
		  filename, id = basename(filename),
		  metadata = c(birthday = as.character(Sys.Date()), package = "frappp", version = as.character(packageVersion("frappp")))
		  ){
		  
		  if (!is.null(self$chunks)) self$chunks <- NULL
		  if (!is.null(self$xml)) self$xml <- NULL
		  if (!is.null(self$html)) self$html <- NULL
		  
		  self$metadata <- metadata
		  
		  self$txt <- readLines(filename)  
		  self$id <- id
		  
		  invisible(self)
		},
		
		
		preprocessing = function(replacements = list(c("[\025]", "\u00A7"), c("\u00A0", " "), c("\a", "\n"))){
		  
		  # remove empty lines
		  emptyLines <- grep("^\\s*$", self$txt)
		  if (length(emptyLines) > 0) self$txt <- self$txt[-emptyLines]
		  
		  # remove leading and trailing whitespace
		  self$txt <- gsub("^\\s*(.*)\\s*$", "\\1", self$txt)
		  
		  # carry out replacements
		  for (replacement in replacements){
		    self$txt <- gsub(replacement[1], replacement[2], self$txt)
		  }
		  
		  # execute document-specific preprocessing functions
		  if (self$id %in% names(self$preprocessingFunctions)){
		    txt <- self$preprocessingFunctions[[self$id]](self$txt)
		  }
		  
		  invisible(self)
		},
		
		addMetadata = function(data){
		  if (is.null(names(data))) stop("the input character vector needs to be named")
		  if (any(names(data) == "")) stop("all elements of the character vector need to be named")
		  if (length(unique(names(data))) != length(names(data))) stop("all names of the character vectors neet to be unique")
		  self$metadata <- c(self$metadata, data)
		  invisible(self)
		},
		
		
